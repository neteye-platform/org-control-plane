"""Tests of the shell steps in plan-core.yaml and apply-core.yaml."""

from __future__ import annotations

import json
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path

from workflow import step_script

WORKFLOW = "plan-core.yaml"

# Prints the units like `terragrunt find --json`, and a text plan for `show`.
FAKE_TERRAGRUNT = """#!/bin/sh
case "$1" in
  find) cat "$FIND_OUTPUT" ;;
  stack) echo generated >"$STACK_GENERATED" ;;
  show)
    echo "dir $3, plan $6"
    case "$3" in *broken*) exit 1 ;; esac ;;
  *) exit 1 ;;
esac
"""


class StepTest(unittest.TestCase):
    def setUp(self):
        self.root = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, self.root)

    def add(self, path: str) -> None:
        file = self.root / path
        file.parent.mkdir(parents=True, exist_ok=True)
        file.write_text("{}\n", encoding="utf-8")

    def run_step(self, step: str, **env: str) -> subprocess.CompletedProcess:
        output = self.root / "github-output"
        output.write_text("", encoding="utf-8")
        return subprocess.run(
            ["bash", "-c", step_script(WORKFLOW, step, "run")],
            cwd=self.root,
            env={
                "PATH": f"{self.root / 'bin'}:/usr/bin:/bin:/usr/local/bin",
                "GITHUB_OUTPUT": str(output),
                **env,
            },
            stdin=subprocess.DEVNULL,
            capture_output=True,
            text=True,
            check=False,
        )

    def fake_terragrunt(self, units: list) -> dict:
        bin_dir = self.root / "bin"
        bin_dir.mkdir(exist_ok=True)
        (bin_dir / "terragrunt").write_text(FAKE_TERRAGRUNT, encoding="utf-8")
        (bin_dir / "terragrunt").chmod(0o755)
        find = self.root / "find.json"
        find.write_text(json.dumps(units), encoding="utf-8")
        return {
            "FIND_OUTPUT": str(find),
            "STACK_GENERATED": str(self.root / "stack-generated"),
        }


class LayoutChecksTest(StepTest):
    def setUp(self):
        super().setUp()
        for path in (
            "repositories/_defaults.yaml",
            "repositories/ai/_defaults.yaml",
            "repositories/ai/tutor.yaml",
            "repositories/projects/_defaults.yaml",
            "repositories/projects/classis.yaml",
            "repositories/projects/pg-otel.yaml",
            # Generated by Terragrunt, never a category.
            "repositories/.terragrunt-stack/ai/terragrunt.hcl",
            "repositories/.terragrunt-stack/_defaults.yaml",
        ):
            self.add(path)

    def test_every_category_has_a_defaults_file(self):
        step = "Check that every category has a defaults file"
        self.assertEqual(self.run_step(step).returncode, 0)

        self.add("repositories/no-defaults-1/repo.yaml")
        (self.root / "repositories/no-defaults-2").mkdir()
        result = self.run_step(step)
        self.assertEqual(result.returncode, 1)
        self.assertIn("::error::Directories without _defaults.yaml:", result.stdout)
        self.assertIn("repositories/no-defaults-1", result.stdout)
        self.assertIn("repositories/no-defaults-2", result.stdout)
        self.assertEqual(len(result.stdout.strip().splitlines()), 1)

    def test_duplicate_repository_names(self):
        step = "Check for duplicate repository names"
        self.assertEqual(self.run_step(step).returncode, 0)

        self.add("repositories/.terragrunt-stack/ai/tutor.yaml")
        self.assertEqual(self.run_step(step).returncode, 0)

        self.add("repositories/ai/classis.yaml")
        result = self.run_step(step)
        self.assertEqual(result.returncode, 1)
        self.assertIn(
            "::error::Duplicate repository files: classis.yaml", result.stdout
        )

    def test_duplicate_repository_names_ignore_the_case(self):
        self.add("repositories/ai/Mentor.yaml")
        self.add("repositories/projects/mentor.yaml")
        result = self.run_step("Check for duplicate repository names")
        self.assertEqual(result.returncode, 1)
        self.assertIn("::error::Duplicate repository files:", result.stdout)

    def test_file_extensions(self):
        step = "Check file extensions"
        self.add("repositories/terragrunt.stack.hcl")
        self.add("teams/teams/admins.yaml")
        self.add("repositories/ai/.terragrunt-cache/x/main.tf")
        self.assertEqual(self.run_step(step).returncode, 0)

        self.add("repositories/ai/new.yml")
        self.add("teams/teams/devs.yml")
        result = self.run_step(step)
        self.assertEqual(result.returncode, 1)
        self.assertIn("::error::Files that are not .yaml:", result.stdout)
        self.assertIn("repositories/ai/new.yml", result.stdout)
        self.assertIn("teams/teams/devs.yml", result.stdout)


class MaskCredentialsTest(StepTest):
    def fake_aws(self, values: list | None) -> dict:
        """`aws ssm get-parameters-by-path` prints `values`, or fails if None."""
        bin_dir = self.root / "bin"
        bin_dir.mkdir(exist_ok=True)
        output = self.root / "aws-output.json"
        output.write_text(json.dumps(values), encoding="utf-8")
        (bin_dir / "aws").write_text(
            '#!/bin/sh\necho "$@" >"$AWS_ARGS"\n'
            '[ "$(cat "$AWS_OUTPUT")" = null ] && exit 254\ncat "$AWS_OUTPUT"\n',
            encoding="utf-8",
        )
        (bin_dir / "aws").chmod(0o755)
        return {
            "AWS_OUTPUT": str(output),
            "AWS_ARGS": str(self.root / "aws-args"),
            "SSM_PREFIX": "/control-plane",
            "SECRETS": str(self.root / "secrets"),
        }

    def test_masks_every_line_of_every_value(self):
        env = self.fake_aws(
            [
                "123",
                "-----BEGIN KEY-----\r\nAAA\r\nBBB\r\n-----END KEY-----\r\n",
                "billing@example.com",
            ]
        )
        result = self.run_step("Mask credentials", **env)
        self.assertEqual(result.returncode, 0, result.stderr)
        lines = [
            "-----BEGIN KEY-----",
            "-----END KEY-----",
            "123",
            "AAA",
            "BBB",
            "billing@example.com",
        ]
        self.assertEqual(
            sorted(result.stdout.splitlines()), [f"::add-mask::{v}" for v in lines]
        )
        self.assertEqual(
            sorted((self.root / "secrets").read_text(encoding="utf-8").splitlines()),
            lines,
        )
        self.assertEqual((self.root / "secrets").stat().st_mode & 0o777, 0o600)
        args = (self.root / "aws-args").read_text(encoding="utf-8").split()
        self.assertIn("--with-decryption", args)
        self.assertIn("--recursive", args)
        self.assertEqual(args[args.index("--path") + 1], "/control-plane")

    def test_fails_without_parameters(self):
        result = self.run_step("Mask credentials", **self.fake_aws([]))
        self.assertEqual(result.returncode, 1)
        self.assertIn("::error::No SSM parameter under /control-plane", result.stdout)

    def test_fails_when_aws_fails(self):
        result = self.run_step("Mask credentials", **self.fake_aws(None))
        self.assertNotEqual(result.returncode, 0)
        self.assertNotIn("::add-mask::", result.stdout)

    def test_plan_and_apply_mask_in_the_same_way(self):
        self.assertEqual(
            step_script("plan-core.yaml", "Mask credentials", "run"),
            step_script("apply-core.yaml", "Mask credentials", "run"),
        )


class ShowPlansTest(StepTest):
    def test_units_and_text_plans(self):
        env = self.fake_terragrunt(
            [
                {"type": "unit", "path": "org-settings"},
                {"type": "stack", "path": "repositories"},
                {"type": "unit", "path": "repositories/.terragrunt-stack/ai"},
                {"type": "unit", "path": "broken"},
                {"type": "unit", "path": "teams"},
            ]
        )
        plans = self.root / "plans"
        # The plan of org-settings failed: it has no tfplan.json.
        self.add("plans/repositories/.terragrunt-stack/ai/tfplan.json")
        self.add("plans/teams/tfplan.json")
        # `terragrunt show` fails for this unit: no partial text plan.
        self.add("plans/broken/tfplan.json")
        (plans / "org-settings").mkdir()

        result = self.run_step("Show plans", PLANS=str(plans), **env)
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertTrue((self.root / "stack-generated").exists())

        name, value = (
            (self.root / "github-output")
            .read_text(encoding="utf-8")
            .strip()
            .split("=", 1)
        )
        self.assertEqual(name, "units")
        self.assertEqual(
            json.loads(value),
            [
                {"unit": "org-settings", "dir": "org-settings"},
                {"unit": "repositories/ai", "dir": "repositories/.terragrunt-stack/ai"},
                {"unit": "broken", "dir": "broken"},
                {"unit": "teams", "dir": "teams"},
            ],
        )
        self.assertIn("::error::Cannot show the plan of broken", result.stdout)
        self.assertFalse((plans / "broken/tfplan.txt").exists())
        ai = plans / "repositories/.terragrunt-stack/ai"
        self.assertEqual(
            (ai / "tfplan.txt").read_text(encoding="utf-8"),
            f"dir repositories/.terragrunt-stack/ai, plan {ai / 'tfplan.tfplan'}\n",
        )
        self.assertTrue((plans / "teams/tfplan.txt").exists())
        self.assertFalse((plans / "org-settings/tfplan.txt").exists())


if __name__ == "__main__":
    unittest.main()
